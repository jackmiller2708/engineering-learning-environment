import { parseWorkspaceId, type WorkspaceId } from './id';
import { validateWorkspaceName, type WorkspaceName, type WorkspaceNameError } from './name';
import { err, ok, type Result } from './result';
import { formatTimestamp, type Timestamp, type TimestampError } from './timestamp';

export const WORKSPACE_SCHEMA_VERSION = 1;

/** A valid workspace record. The branded field types make it hard to build one without validation. */
export interface Workspace {
  readonly schemaVersion: typeof WORKSPACE_SCHEMA_VERSION;
  readonly id: WorkspaceId;
  readonly name: WorkspaceName;
  readonly createdAt: Timestamp;
}

/** Which field is wrong and why. */
export type WorkspaceError =
  | { readonly field: 'id'; readonly code: 'invalid_id' }
  | { readonly field: 'name'; readonly code: WorkspaceNameError }
  | { readonly field: 'createdAt'; readonly code: TimestampError };

export interface NewWorkspace {
  /** Generated by the caller (the domain does no random generation). */
  readonly id: string;
  /** Raw user input; validated and trimmed here. */
  readonly name: string;
  /** The current time, supplied by the caller (the domain does not read the clock). */
  readonly now: Date;
}

/** Pure. Reports the first problem in the order id, name, createdAt. */
export function createWorkspace(input: NewWorkspace): Result<Workspace, WorkspaceError> {
  const id = parseWorkspaceId(input.id);
  if (!id.ok) return err({ field: 'id', code: id.error });
  const name = validateWorkspaceName(input.name);
  if (!name.ok) return err({ field: 'name', code: name.error });
  const createdAt = formatTimestamp(input.now);
  if (!createdAt.ok) return err({ field: 'createdAt', code: createdAt.error });
  return ok({ schemaVersion: WORKSPACE_SCHEMA_VERSION, id: id.value, name: name.value, createdAt: createdAt.value });
}
